type RuntimeReportJob = {
  id: string;
  name: string;
  workload: string;
  status: "queued" | "running" | "completed" | "failed";
  createdAt: string;
  completedAt?: string;
  progress: number;
  result?: {
    totalRows: number;
    columns: string[];
    rows: string[][];
    metrics: GeneratedReport["metrics"];
  };
  error?: string;
};

const delay = (milliseconds: number) =>
  new Promise((resolve) => setTimeout(resolve, milliseconds));

export async function runRuntimeReport(
  name: string,
  workload: string,
  columns?: string[],
): Promise<GeneratedReport> {
  let job = await request<RuntimeReportJob>("/api/v1/report-jobs", {
    method: "POST",
    body: JSON.stringify({ name, workload, columns }),
  });
  for (
    let attempt = 0;
    attempt < 40 && job.status !== "completed" && job.status !== "failed";
    attempt++
  ) {
    await delay(150);
    job = await request<RuntimeReportJob>(`/api/v1/report-jobs/${job.id}`);
  }
  if (job.status !== "completed" || !job.result)
    throw new Error(
      job.error ?? "Report job did not complete within the acceptance timeout.",
    );
  return {
    id: job.id,
    name: job.name,
    workload: job.workload,
    description:
      "Generated by the persistent local report-job runtime from seeded tenant resources.",
    generatedAt: job.completedAt ?? job.createdAt,
    sourceFreshness: "real-time local runtime",
    totalRows: job.result.totalRows.toLocaleString("en-US"),
    columns: job.result.columns,
    rows: job.result.rows,
    metrics: job.result.metrics,
  };
}

type RuntimeWorkflow = {
  id: string;
  title: string;
  state:
    | "draft"
    | "pending_approval"
    | "approved"
    | "running"
    | "completed"
    | "failed"
    | "rolled_back";
  execution?: {
    affected: number;
    succeeded: number;
    failed: number;
    message: string;
  };
};

export async function runRuntimeWorkflow(
  title: string,
  targetScope: string,
  justification: string,
) {
  let workflow = await request<RuntimeWorkflow>(
    "/api/v1/workflows",
    {
      method: "POST",
      body: JSON.stringify({
        title,
        type: "governed-demo-operation",
        targetScope,
        justification,
      }),
    },
    "admin@apex.local",
  );
  workflow = await request<RuntimeWorkflow>(
    `/api/v1/workflows/${workflow.id}/submit`,
    { method: "POST", body: "{}" },
    "admin@apex.local",
  );
  workflow = await request<RuntimeWorkflow>(
    `/api/v1/workflows/${workflow.id}/approve`,
    {
      method: "POST",
      body: JSON.stringify({ comment: "Acceptance environment approval" }),
    },
    "security.approver@apex.local",
  );
  workflow = await request<RuntimeWorkflow>(
    `/api/v1/workflows/${workflow.id}/execute`,
    { method: "POST", body: "{}" },
    "workflow.engine@apex.local",
  );
  for (
    let attempt = 0;
    attempt < 40 && workflow.state === "running";
    attempt++
  ) {
    await delay(150);
    workflow = await request<RuntimeWorkflow>(
      `/api/v1/workflows/${workflow.id}`,
    );
  }
  return workflow;
}

