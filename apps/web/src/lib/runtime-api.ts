import type { GeneratedReport } from "@/lib/reporting";

const API = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:3001";
const TENANT = "00000000-0000-4000-8000-000000000001";

function headers(actor = "admin@apex.local") {
  return {
    "Content-Type": "application/json",
    "x-tenant-id": TENANT,
    "x-actor-id": actor,
    "x-platform-roles": "platform-admin,security-admin",
  };
}

async function request<T>(
  path: string,
  init?: RequestInit,
  actor?: string,
): Promise<T> {
  const response = await fetch(`${API}${path}`, {
    ...init,
    headers: { ...headers(actor), ...(init?.headers ?? {}) },
  });
  if (!response.ok) {
    const body = await response
      .json()
      .catch(() => ({ message: response.statusText }));
    throw new Error(
      Array.isArray(body.message)
        ? body.message.join(", ")
        : body.message || `API request failed (${response.status})`,
    );
  }
  return response.json() as Promise<T>;
}

